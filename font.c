/* ---- Draw one character ---- */
void font_char(GSGLOBAL *gs, int x, int y, unsigned char c, u64 color) {
    if (c < 32 || c > 126) c = '?';
    const unsigned char *g = FONT5x7[c - 32];

    for (int col = 0; col < 5; col++) {
        unsigned char bits = g[col];
        for (int row = 0; row < 7; row++) {
            if (bits & (1 << row)) {
                int px = x + col * FONT_SCALE;
                int py = y + row * FONT_SCALE;
                gsKit_prim_sprite(gs, px, py, px + FONT_SCALE, py + FONT_SCALE, 1, color);
            }
        }
    }
}

/* ---- printf-style string ---- */
void font_printf(GSGLOBAL *gs, int x, int y, u64 color, const char *fmt, ...) {
    char buf[256];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    int cx = x;
    for (int i = 0; buf[i]; i++) {
        font_char(gs, cx, y, (unsigned char)buf[i], color);
        cx += FONT_PIX_W;
    }
}

/* ---- Centered on a 640-px-wide screen ---- */
void font_printf_center(GSGLOBAL *gs, int y, u64 color, const char *fmt, ...) {
    char buf[256];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);

    int w = (int)strlen(buf) * FONT_PIX_W;
    int x = (640 - w) / 2;
    if (x < 0) x = 0;

    font_printf(gs, x, y, color, "%s", buf);
}

/* ---- Measure string width in pixels ---- */
int font_width(const char *s) {
    return (int)strlen(s) * FONT_PIX_W;
}